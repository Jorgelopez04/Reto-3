        .MODEL SMALL
        .386
       	.STACK
        .DATA
VECTOR1 DB      10 DUP('*'),'$'
VECTOR2 DB      10 DUP('*'),'$'
;M1	DB	10,13,'CONTENIDO INICIAL DEL VECTOR: $'
M2      DB      10,10,13,'INGRESE 10 CARACTERES: $'
M3      DB      10,10,10,13,'CONTENIDO DESPUES DE INGRESO: $'

	.CODE
	ORG	0000
	JMP	MAIN

INICIO:	MOV	AX,@DATA
	MOV	DS,AX
	RET
VIS_MENS:
	MOV	AH,09H
	INT	21H
	RET

INGRESO:
	MOV	AH,01H
	INT	21H
	RET

LLENAR_VECTOR1:
	MOV	SI,0
	MOV	CX,10
	MOV	DX,OFFSET M2
	CALL	VIS_MENS
CICLO:	CALL	INGRESO
        MOV     VECTOR1[SI],AL
	INC	SI
	LOOP	CICLO
	RET
LLENAR_VECTOR2:
	MOV	SI,0
	MOV	CX,10
	MOV	DX,OFFSET M2
	CALL	VIS_MENS
CICLO:	CALL	INGRESO
        MOV     VECTOR2[SI],AL
	INC	SI
	LOOP	CICLO
	RET

MAIN:	CALL	INICIO
;	MOV	DX,OFFSET M1
;	CALL	VIS_MENS
        MOV     DX,OFFSET VECTOR1
	CALL	VIS_MENS
        CALL    LLENAR_VECTOR1
	MOV	DX,OFFSET M3
	CALL	VIS_MENS
        MOV     DX,OFFSET VECTOR2
	CALL	VIS_MENS
;        MOV     DX,OFFSET VECTOR
	CALL	VIS_MENS
        CALL    LLENAR_VECTOR2
	MOV	DX,OFFSET M3
	CALL	VIS_MENS
        MOV     DX,OFFSET VECTOR2
	CALL	VIS_MENS
	MOV	AH,4CH
	INT	21H

	END


